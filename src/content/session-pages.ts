/**
 * Single source of truth for the wording of the family-facing session pages
 * ("לקראת המפגש שלנו"). Inbal approves the copy here; components never inline
 * Hebrew prose of their own, so a wording fix never touches JSX.
 *
 * All three pages - first session, intake, parents meeting - are the same
 * `SessionPageContent` shape rendered by `SessionPage`. Adding a fourth page
 * means adding an object here and a three-line route.
 */

export type AudienceKey = "parents" | "crisis" | "guidance";
export type LocationKey = "alfei-menashe" | "home" | "online";
export type PaymentKey = "bit" | "paybox" | "credit" | "transfer" | "cash";

export interface InfoCard {
  title: string;
  body: string;
}

export interface AudienceNote {
  key: AudienceKey;
  label: string;
  body: string[];
}

export interface FaqItem {
  question: string;
  answer: string;
}

export interface SessionLocation {
  key: LocationKey;
  name: string;
  address: string;
}

/**
 * One block on a page. Consecutive sections sharing a `tone` are rendered as a
 * single colour band, with a warm rule wherever the tone changes.
 */
export interface PageSection {
  id: string;
  tone?: "plain" | "tinted";
  title?: string;
  subtitle?: string;
  paragraphs?: string[];
  cards?: InfoCard[];
  /** Rendered filtered by the `audience` URL parameter. */
  audienceNotes?: AudienceNote[];
}

export interface SessionPageContent {
  slug: string;
  pageTitle: string;
  metaTitle: string;
  metaDescription: string;
  hero: { greeting: string; paragraphs: string[] };
  sections: PageSection[];
  /**
   * The cancellation terms are stated once, on the page a family reads on the
   * way in. Repeating them on every later page turns a practical note into a
   * warning that follows them through the process.
   */
  showCancellationPolicy: boolean;
  faq: FaqItem[];
  personalNote: {
    title: string;
    paragraphs: string[];
    signOff: string;
    signature: string;
    credentials: string;
  };
  /** Pre-filled text for the WhatsApp button at the foot of the page. */
  whatsappMessage: string;
}

